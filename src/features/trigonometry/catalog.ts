const EPSILON = 1e-10

const evaluators = {
  sin: Math.sin,
  cos: Math.cos,
  tan: Math.tan,
  cot: (x: number) => 1 / Math.tan(x),
  sec: (x: number) => 1 / Math.cos(x),
  csc: (x: number) => 1 / Math.sin(x),
  arcsin: Math.asin,
  arccos: Math.acos,
  arctan: Math.atan,
  arccot: (x: number) => Math.atan2(1, x) > 0 ? Math.atan2(1, x) : Math.atan2(1, x) + Math.PI,
  arcsec: (x: number) => Math.acos(1 / x),
  arccsc: (x: number) => Math.asin(1 / x),
} satisfies Record<FunctionId, (x: number) => number>

const isFiniteReal = (x: number) => Number.isFinite(x)
const isUnitInterval = (x: number) =>
  Number.isFinite(x) && x >= -1 && x <= 1
const isOutsideUnitInterval = (x: number) =>
  Number.isFinite(x) && Math.abs(x) >= 1

