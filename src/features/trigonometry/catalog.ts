const functionDefinitionById = new Map<FunctionId, FunctionDefinition>(
  functionCatalog.map(definition => [definition.id, definition]),
)

export function getFunctionDefinition(id: FunctionId): FunctionDefinition {
  const definition = functionDefinitionById.get(id)

  if (!definition) {
    throw new Error(`未知函数 ID：${id}`)
  }

  return definition
}
